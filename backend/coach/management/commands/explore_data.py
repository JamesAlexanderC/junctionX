"""P1.1: profile the S-Bank CSVs and write docs/data_profile.md."""

from collections import Counter
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from coach.management import csvdata

MAPPING_NOTES = [
    "",
    "## Vocabulary mapping (inferences/thresholds.py)",
    "",
    "- Sign convention: inflow > 0 (salary 100% positive, purchases 100% negative).",
    "- Essentials: groceries, housing, utilities, health; transportation only for",
    "  MCC 4111/4112/4131 (public transport), 5541/5542 (fuel), 7523 (parking)",
    "  or a blank MCC. Taxis (4121) are other spending.",
    "- salary_sweep: neutral own-account transfer (not spending, not Saver).",
    "  retained_income = salary - sweep drives budgeting maths (#10, #17, #88).",
    "  coverage = sweep / salary; above 0.5 the profile is a partial view and is",
    "  excluded from peer benchmarks.",
    "- investment_deposit = Saver; investment_withdrawal = negative Saver (#94).",
    "- #58 travel goal uses category == travel.",
    "- The reference date is max(tx_date), not the wall-clock date.",
    "- No loan, credit-card, fee or gambling values exist in the real data.",
    "  #76-#84 and #86 run on the synthetic credit register and injected events",
    "  only; those must use the labels in LOAN_CATEGORIES / FEE_CATEGORIES.",
]


class Command(BaseCommand):
    help = "Print counts, values and sign convention of the CSVs (chunked)."

    def add_arguments(self, parser):
        parser.add_argument("--data-dir")
        parser.add_argument(
            "--out", default=str(settings.BASE_DIR.parent / "docs" / "data_profile.md")
        )

    def handle(self, *args, **opts):
        data_dir = Path(opts["data_dir"]) if opts["data_dir"] else None
        rows = 0
        cats, types_, mccs = Counter(), Counter(), Counter()
        accounts = {}
        pos = neg = 0
        dmin = dmax = None
        sign_by_type = {}
        for chunk in csvdata.iter_transactions(data_dir):
            rows += len(chunk)
            cats.update(chunk["category"].value_counts().to_dict())
            types_.update(chunk["transaction_type"].value_counts().to_dict())
            mccs.update(chunk["mcc_code"].value_counts().to_dict())
            pos += int((chunk["tx_amount_eur"] > 0).sum())
            neg += int((chunk["tx_amount_eur"] < 0).sum())
            lo, hi = chunk["tx_date"].min(), chunk["tx_date"].max()
            dmin = lo if dmin is None else min(dmin, lo)
            dmax = hi if dmax is None else max(dmax, hi)
            for cid, acc in chunk[["customer_id", "bank_account_id"]].values:
                accounts.setdefault(cid, set()).add(acc)
            grp = chunk.groupby("transaction_type")["tx_amount_eur"]
            for t, s in grp.agg(lambda x: (x > 0).mean()).items():
                sign_by_type.setdefault(t, []).append(s)
        multi = sum(1 for a in accounts.values() if len(a) > 1)
        lines = [
            "# S-Bank data profile",
            "",
            "Generated by `manage.py explore_data`.",
            "",
            f"- Transactions: {rows}",
            f"- Customers with transactions: {len(accounts)}",
            f"- Date range: {dmin:%Y-%m-%d} to {dmax:%Y-%m-%d}" if rows else "",
            f"- Positive amounts: {pos}, negative amounts: {neg}",
            f"- Customers with more than one bank_account_id: {multi}",
            "",
        ]
        for name, path in (
            ("Customers", csvdata.CUSTOMERS_FILE),
            ("Mortgage history", csvdata.MTG_HISTORY_FILE),
            ("Mortgage link", csvdata.MTG_LINK_FILE),
        ):
            try:
                df = csvdata.read_small(path, data_dir)
                lines.append(
                    f"- {name}: {len(df)} rows, columns: {', '.join(df.columns)}"
                )
            except Exception as exc:  # noqa: BLE001 - report and continue
                lines.append(f"- {name}: not readable ({exc})")
        lines += ["", "## category", "", "| value | count |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in cats.most_common()]
        lines += [
            "",
            "## transaction_type (share of positive amounts)",
            "",
            "| value | count | share > 0 |",
            "|---|---|---|",
        ]
        for k, v in types_.most_common():
            shares = sign_by_type.get(k, [0])
            lines.append(f"| {k} | {v} | {sum(shares) / len(shares):.2f} |")
        lines += ["", "## top 30 mcc_code", "", "| mcc | count |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in mccs.most_common(30)]
        lines += MAPPING_NOTES
        text = "\n".join(lines) + "\n"
        out = Path(opts["out"])
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        self.stdout.write(text)
        self.stdout.write(self.style.SUCCESS(f"Wrote {out}"))
